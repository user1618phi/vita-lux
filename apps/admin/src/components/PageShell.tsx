import type { ReactNode } from "react";
import { AppShell } from "./AppShell";

/* Переходник со старого каркаса на новый.

   Живёт ОТДЕЛЬНО от `app/ui.tsx` и это не вкусовщина: `ui.tsx` импортируют
   клиентские компоненты (форма входа, редактор товара), а `AppShell` тянет за
   собой `lib/auth` с `server-only` и `next/headers`. Один общий модуль на
   серверное и клиентское — ровно тот «бочонок», от которого в проекте
   отказались: сборка падает с «server-only in a Client Component».

   Экраны, ещё не переписанные под таблицы, зовут `PageShell` и через него
   получают то же меню и ту же шапку, что и новые. Когда переедет последний,
   этот файл исчезнет. */

export function PageShell({
  title,
  aside,
  children,
}: {
  title: string;
  aside?: ReactNode;
  /** Больше не используется: навигацию рисует каркас. Оставлен, чтобы не
      править разом восемь страниц ради удаления одного пропа. */
  nav?: ReactNode;
  /** Ширину теперь задаёт каркас — экраны стали широкими все. */
  width?: "narrow" | "wide";
  children: ReactNode;
}) {
  /* Переходник на `AppShell`.

     Раньше это была самостоятельная колонка на 640px с горизонтальным
     рельсом вкладок сверху. Экраны, которые ещё не переписаны под таблицы,
     продолжают звать `PageShell` — и через него получают то же боковое меню и
     ту же шапку, что и новые. Когда последний из них переедет на `AppShell`
     напрямую, этот переходник исчезнет. */
  return (
    <AppShell title={title} actions={aside}>
      {children}
    </AppShell>
  );
}
