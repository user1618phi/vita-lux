/* Готовность товара к продаже — чистые правила, без базы.

   Пять требований, каждое либо закрыто, либо нет:

     имя      — в X2pos 36 товаров называются «Унитаз», такое имя витрине не
                годится, поэтому осмысленным считается только то, что отличается
                от артикула
     раздел   — товар лежит не в служебной категории `x2pos-inbox`
     фото     — есть хотя бы одна карточка media
     цена     — есть действующая розничная цена; без неё витрина рисует
                «Цена по запросу» и не даёт положить в корзину
     остаток  — на складе что-то есть

   Опубликовать можно, когда закрыты ПЕРВЫЕ ДВА — имя и раздел.

   Раньше требовались ещё фото и цена, и это было верно, пока витрина не умела
   их отсутствие показывать: товар без цены рисовал «0 ₸» и продавался, товар
   без фото — пустой серый квадрат. Оба состояния теперь имеют собственный вид:
   «Цена по запросу» рядом с кнопкой «Спросить в WhatsApp» и подпись «Фото скоро
   появится». То есть это больше не дефекты карточки, а нормальные состояния
   товара, который есть на складе и который можно купить, списавшись с магазином.

   Держать такой товар скрытым значило бы прятать существующий ассортимент —
   покупатель не найдёт его ни поиском, ни в разделе, хотя магазин им торгует.

   Имя и раздел остаются обязательными: без них у страницы нет ни заголовка, ни
   адреса в каталоге — показывать нечего.

   Проверки `photo`, `price` и `stock` никуда не делись: админка по-прежнему
   рисует их как незакрытые задачи, просто они больше не запирают витрину.

   Правила живут в @vita/core, а не в админке, потому что потребителей двое:
   экран «Готовы к публикации» и скрипт наполнения каталога, который решает,
   какие черновики имеет право включить. Две копии этого условия разошлись бы
   на первой же правке, и разошлись бы молча — в сторону публикации товара,
   который не готов. Запрос в базу остался в админке: она умеет ходить в БД,
   а домен — нет. */

export const INBOX_SLUG = "x2pos-inbox";

export interface ReadinessInput {
  name: string;
  sku: string | null;
  categorySlug: string;
  retailKzt: number | null;
  qty: number | null;
  photos: number;
}

export interface Checks {
  name: boolean;
  category: boolean;
  photo: boolean;
  price: boolean;
  stock: boolean;
}

export function checksFor(p: ReadinessInput): Checks {
  const article = (p.sku ?? "").trim().toLowerCase();
  const name = p.name.trim().toLowerCase();
  return {
    /* Имя, совпадающее с артикулом, — это заглушка, которую поставил синк. */
    name: name.length > 0 && name !== article && !name.startsWith("x2pos "),
    category: p.categorySlug !== INBOX_SLUG,
    photo: p.photos > 0,
    price: p.retailKzt !== null,
    stock: (p.qty ?? 0) > 0,
  };
}

/** Можно ли публиковать. Фото, цена и остаток — задачи, а не блокировки. */
export function publishable(c: Checks): boolean {
  return c.name && c.category;
}
