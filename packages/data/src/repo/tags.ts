/* Имена кэш-тегов и словарь того, что вообще можно инвалидировать.

   Модуль намеренно ПУСТОЙ по зависимостям: ни `server-only`, ни `next/cache`,
   ни каталога. Его импортируют трое, и у каждого своя причина:

   - витрина — чтобы пометить `unstable_cache`;
   - админка — чтобы назвать тег, который надо сбросить;
   - роут `/api/revalidate` на витрине — чтобы проверить пришедший тег.

   Если бы теги остались в `repo/index.ts`, админка вместе с двумя строковыми
   константами затягивала бы в свой бандл весь мок-каталог и драйвер Postgres, а
   `pickSource()` там выполняется на уровне модуля и бросает при неудачной
   комбинации переменных окружения — то есть все экшены админки падали бы из-за
   импорта, к которому не имеют отношения. */

/** Весь каталог: списки категорий, хиты, фильтры. */
export const CATALOG_TAG = "catalog";

/** Настройки магазина: телефоны, доставка, рассрочка. */
export const SETTINGS_TAG = "settings";

/** Один товар. Хендл — часть URL витрины. */
export const productTag = (handle: string) => `product:${handle}`;

/** Путь роута ревалидации на витрине. Держим рядом с тегами, чтобы отправитель
    и получатель не разъехались. */
export const REVALIDATE_PATH = "/api/revalidate";

/** Потолок на один вызов. Существует, чтобы чужой запрос не заставил витрину
    перебрать произвольно длинный список. */
export const MAX_TAGS_PER_CALL = 50;

/* Та же регулярка, что валидирует handle в форме товара (apps/admin actions.ts).
   Держать её здесь — единственный способ проверить тег на стороне витрины, не
   импортируя туда админские схемы. */
const HANDLE_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

/** Известен ли тег. Всё, что не описано здесь, витрина обязана отвергнуть:
    роут публичный, и принимать произвольные строки из сети в `revalidateTag`
    незачем. */
export function isKnownTag(tag: string): boolean {
  if (tag === CATALOG_TAG || tag === SETTINGS_TAG) return true;
  const handle = tag.startsWith("product:") ? tag.slice("product:".length) : null;
  return handle !== null && HANDLE_RE.test(handle);
}
